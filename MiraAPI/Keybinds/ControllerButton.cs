namespace MiraAPI.Keybinds;

/// <summary>
/// Controller buttons used for default keybinds.
/// </summary>
public enum ControllerButton
{
    /// <summary>
    /// The bottom face button (Cross on PlayStation, A on Xbox).
    /// </summary>
    South = 4,

    /// <summary>
    /// The right face button (Circle on PlayStation, B on Xbox).
    /// </summary>
    East = 5,

    /// <summary>
    /// The left face button (Square on PlayStation, X on Xbox).
    /// </summary>
    West = 7,

    /// <summary>
    /// The top face button (Triangle on PlayStation, Y on Xbox).
    /// </summary>
    North = 8,

    /// <summary>
    /// The left bumper (L1 on PlayStation, LB on Xbox).
    /// </summary>
    LeftBumper = 10,

    /// <summary>
    /// The right bumper (R1 on PlayStation, RB on Xbox).
    /// </summary>
    RightBumper = 12,

    /// <summary>
    /// The left trigger (L2 on PlayStation, LT on Xbox).
    /// </summary>
    LeftTrigger = 11,

    /// <summary>
    /// The right trigger (R2 on PlayStation, RT on Xbox).
    /// </summary>
    RightTrigger = 13,

    /// <summary>
    /// The left stick button (L3 on PlayStation).
    /// </summary>
    LeftStick = 17,

    /// <summary>
    /// The right stick button (R3 on PlayStation).
    /// </summary>
    RightStick = 18,

    /// <summary>
    /// The back button (Create on PlayStation, View on Xbox).
    /// </summary>
    Back = 14,

    /// <summary>
    /// The start button (Options on PlayStation, Menu on Xbox).
    /// </summary>
    Start = 15,

    /// <summary>
    /// The D-pad up button.
    /// </summary>
    DPadUp = 19,

    /// <summary>
    /// The D-pad right button.
    /// </summary>
    DPadRight = 20,

    /// <summary>
    /// The D-pad down button.
    /// </summary>
    DPadDown = 21,

    /// <summary>
    /// The D-pad left button.
    /// </summary>
    DPadLeft = 22,
}
